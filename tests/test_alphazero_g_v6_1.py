def test_selection_uses_dev_only_fixed_precedence_and_keeps_budget_winners_separate() -> None:
    summaries = {}
    for budget, rates in ((64, (0.7, 0.5, 0.4)), (400, (0.4, 0.5, 0.7))):
        summaries[str(budget)] = {
            model: {
                "h2h_rate": rate,
                "h2h_ci95": [max(0, rate - 0.01), min(1, rate + 0.01)],
                "vs_A_minimax_rate": 0.2,
                "vs_B_ab50_rate": 0.1,
                "tactic_puct_accuracy": 0.5,
            }
            for model, rate in zip(("G10K", "G15K", "G20K"), rates)
        }
    selection = make_selection(summaries, frozen_checkpoint_sha256={
        "G10K": "a", "G15K": "b", "G20K": "c",
    })
    assert selection["selected_by_budget"] == {"64": "G10K", "400": "G20K"}
    assert selection["blind_results_used_for_selection"] is False
    assert selection["selection_rule_id"] == "h2h_then_A_then_B_then_tactics"


def test_paired_summary_requires_both_colors_and_reports_reproducible_metrics() -> None:
    games = [
        {"game_id": "xB", "opening_group_id": "o1", "candidate_color": "B", "points": 1,
         "winner_color": "B", "move_count": 20, "candidate_cpu_seconds": 2.0},
        {"game_id": "xW", "opening_group_id": "o1", "candidate_color": "W", "points": 0,
         "winner_color": "B", "move_count": 22, "candidate_cpu_seconds": 3.0},
    ]
    summary = summarize_tournament_games(games, seed=42)
    assert summary["games"] == 2
    assert summary["paired_openings"] == 1
    assert summary["score_rate"] == 0.5
    assert summary["black_score_rate"] == 1.0
    assert summary["white_score_rate"] == 0.0
    assert summary["mean_moves"] == 21
    with pytest.raises(ValueError, match="color-swapped"):
        summarize_tournament_games(games[:1], seed=42)


def test_v6_1_openings_are_fixed_new_legal_and_distinct() -> None:
    root = Path(__file__).resolve().parents[1]
    v61 = root / "research/g_v6_1/config/openings.json"
    if not v61.exists():
        pytest.skip("V6.1 opening registration is generated by register command")
    schedule = json.loads(v61.read_text())
    validate_opening_sets(schedule, root=root)
    assert len(schedule["development"]) == 40
    assert len(schedule["blind"]) == 40


